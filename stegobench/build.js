#!/usr/bin/env node
/* StegoBench - builds js/worker-src.js (the Web Worker bundle).
 * Workers cannot be loaded from file:// in most browsers, so the worker code is embedded as a string and
 * started from a Blob URL. Run `node build.js` after editing any file listed below. */
'use strict';
const fs = require('fs'), path = require('path');
const FILES = ['utils.js', 'codec.js', 'stc.js', 'methods.js', 'attacks.js', 'detectors.js', 'metrics.js', 'job.js'];
const dir = path.join(__dirname, 'js');
let src = "self.window = self;\n";
for (const f of FILES) src += `/* ---- ${f} ---- */\n` + fs.readFileSync(path.join(dir, f), 'utf8') + '\n';
src += `
self.onmessage = async function (e) {
  const { id, job } = e.data;
  try {
    const res = await self.SB.runJob(job);
    self.postMessage({ id, res });
  } catch (err) { self.postMessage({ id, error: String((err && err.message) || err) }); }
};
`;
const out = '/* generated by build.js - do not edit */\nwindow.SB_WORKER_SRC = ' + JSON.stringify(src) + ';\n';
fs.writeFileSync(path.join(dir, 'worker-src.js'), out);
console.log('js/worker-src.js written (' + (out.length / 1024).toFixed(0) + ' KB)');
